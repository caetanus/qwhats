#!/usr/bin/env python3
"""wa/source/wa/binary/dict.d from WhatsApp Web's own WAWapDict module (a downloaded bundle file
or the module on its own): the single-byte tokens and the four double-byte dictionaries of the
binary XML (WAP) format. Run again when WhatsApp moves DICT_VERSION.

    wa/tools/gen-wapdict.py ~/.cache/qml-whats-build/waweb/mods/WAWapDict.js > wa/source/wa/binary/dict.d
"""
import json, re, sys

src = open(sys.argv[1], encoding="utf-8").read()
i = src.index('__d("WAWapDict"')
body = src[i:src.index("}),", i)]
version = int(re.search(r"var e=(\d+)", body).group(1))
arrays = {name: json.loads("[" + val + "]") for name, val in re.findall(r"\b([a-z])=\[(\"[^\]]*)\]", body)}
order = re.search(r"m=\[(\w),(\w),(\w),(\w)\]", body).groups()
single = arrays["l"]
dicts = [arrays[n] for n in order]

def dlist(name, xs):
    lines = []
    row = "    "
    for x in xs:
        item = json.dumps(x, ensure_ascii=False) + ", "
        if len(row) + len(item) > 110:
            lines.append(row.rstrip())
            row = "    "
        row += item
    lines.append(row.rstrip())
    return f"immutable string[] {name} = [\n" + "\n".join(lines) + "\n];\n"

out = ["// Generated by wa/tools/gen-wapdict.py from WhatsApp Web's WAWapDict module: the token tables of",
       "// the binary XML (WAP) format. Do not edit; regenerate when WhatsApp moves DICT_VERSION.",
       "module wa.binary.dict;", "",
       f"enum dictVersion = {version};", "",
       "/// Tokens written as one byte: token i is byte i + 1.",
       dlist("singleByteTokens", single),
       "/// The double-byte dictionaries: byte 236 + d, then the index in dictionary d."]
for k, d in enumerate(dicts):
    out.append(dlist(f"dictionary{k}", d))
out.append("immutable string[][] dictionaries = [dictionary0, dictionary1, dictionary2, dictionary3];")
print("\n".join(out))
