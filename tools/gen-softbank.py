#!/usr/bin/env python3
# Regenerates core/softbank.go: SoftBank private-use emoji → standard emoji, from iamcal/emoji-data
# (https://raw.githubusercontent.com/iamcal/emoji-data/master/emoji.json, its "softbank" field).
# usage: gen-softbank.py emoji.json > core/softbank.go
import json, sys
d = json.load(open(sys.argv[1]))
m = {int(e["softbank"], 16): "".join("\\U%08X" % int(x, 16) for x in e["unified"].split("-")) for e in d if e.get("softbank")}
print("package main\n")
print("// Old iPhones wrote emoji in SoftBank's private-use codes (U+E001–U+E537); names and messages from")
print("// then still carry them, and today's fonts draw boxes. WhatsApp shows the standard emoji: the")
print("// mapping is SoftBank's, from iamcal/emoji-data (generated by tools/gen-softbank.py).\n")
print("var softbank = map[rune]string{")
for k in sorted(m):
    print('\t0x%X: "%s",' % (k, m[k]))
print("}\n")
print('''// unsoftbank: the text with SoftBank emoji as standard emoji (unchanged, and not copied, without any).
func unsoftbank(s string) string {
	found := false
	for _, r := range s {
		if r >= 0xE001 && r <= 0xE537 {
			found = true
			break
		}
	}
	if !found {
		return s
	}
	var b []rune
	for _, r := range s {
		if e, ok := softbank[r]; ok {
			b = append(b, []rune(e)...)
		} else {
			b = append(b, r)
		}
	}
	return string(b)
}''')
