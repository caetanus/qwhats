#!/bin/bash
# Builds QWhats against Qt's own 6.11.2 binaries inside the manylinux_2_34 build image
# (tools/manylinux/Containerfile: AlmaLinux 9, glibc 2.34, clang, LDC 1.43, meson) and makes the
# AppImage, which then runs on any distribution with glibc >= 2.34. Used by tools/manylinux.sh
# (podman) and by the GitHub workflow (.github/workflows/appimage.yml).
#
# Paths come from the environment:
#   APP   this repository                  (default /src/qml-whats)
#   SQ    a solid-qml checkout (branch widgets, with its qml-css-engine submodule)
#                                          (default /src/solid-qml-native)
#   QT    Qt 6.11.2 gcc_64 (aqtinstall)    (default /qt/6.11.2/gcc_64)
#   WORK  build directories, step stamps   (default /work)   OUT  where the AppImage goes (/out)
#   TOOLS linuxdeploy (+ plugin-qt) and appimagetool AppImages, downloaded when missing (/tools)
# The DSide binding and the solid-qml host come from third_party/solid-qml-d (tools/update-binding.sh).
# Each step leaves a stamp in WORK; a rerun resumes after the last one that succeeded.
set -euo pipefail
APP=${APP:-/src/qml-whats}
SQ=${SQ:-/src/solid-qml-native}
Q=${QT:-/qt/6.11.2/gcc_64}
W=${WORK:-/work}
OUT=${OUT:-/out}
TOOLS=${TOOLS:-/tools}
JOBS=${JOBS:-6}
mkdir -p "$W" "$OUT" "$TOOLS"
export PATH=$Q/bin:/opt/ldc/bin:/opt/python/cp312-cp312/bin:$PATH
export PKG_CONFIG_PATH=$Q/lib/pkgconfig
export TMPDIR=$W/tmp; mkdir -p "$TMPDIR"
step() { [ -e "$W/.done-$1" ]; }
done_() { touch "$W/.done-$1"; echo "== $1 done"; }

# ---- libsolidqml (solid-qml's meson build, the library target only) ------------------------------
if ! step solidqml; then
    rm -rf "$W/solidqml"
    CXX=g++ meson setup "$W/solidqml" "$SQ" --buildtype=release -Dwarning_level=0 >"$W/solidqml-setup.log" 2>&1 \
        || { tail -30 "$W/solidqml-setup.log"; exit 1; }
    meson compile -C "$W/solidqml" -j "$JOBS" solidqml >"$W/solidqml-build.log" 2>&1 \
        || { grep -E "error" "$W/solidqml-build.log" | head -30; exit 1; }
    done_ solidqml
fi

# ---- the DSide binding, generated by xiboca for the same Qt (6.11.2): only compiled here ---------
SQD=$APP/third_party/solid-qml-d
GEN=$W/gen
B=$W/binding
MODS="Qt6Quick Qt6QmlModels Qt6Qml Qt6Gui Qt6Network Qt6DBus Qt6Multimedia Qt6Core"
if ! step shims; then
    rm -rf "$GEN"; cp -r "$SQD/generated/qt-6.11/solidqml" "$GEN"
    sed -i -e "s#@SOLIDQML@/#$SQ/#g" -e "s#@QTINC@/#$Q/include/#g" "$GEN"/*.cpp
    rm -rf "$B"; mkdir -p "$B/ocpp"
    CFLAGS=$(pkg-config --cflags $MODS)
    PRIV=""
    for m in QtCore QtGui QtQml QtQmlModels QtQuick QtNetwork QtDBus QtMultimedia; do
        PRIV="$PRIV -I$Q/include/$m/6.11.2 -I$Q/include/$m/6.11.2/$m"
    done
    for c in "$GEN"/*.cpp; do
        b=$(basename "$c" .cpp)
        clang++ $CFLAGS $PRIV -I"$SQ/src" -std=c++17 -fPIC -O2 -ffunction-sections -fdata-sections -w \
            -c "$c" -o "$B/ocpp/$b.o" &
        while [ "$(jobs -r | wc -l)" -ge "$JOBS" ]; do sleep 1; done
    done
    wait
    [ "$(ls "$B"/ocpp/*.o | wc -l)" = "$(ls "$GEN"/*.cpp | wc -l)" ] || { echo "a shim did not compile"; exit 1; }
    ar rcs "$B/libshims.a" "$B"/ocpp/*.o
    done_ shims
fi
if ! step binding; then
    # in batches: one ldc2 over all ~1000 modules holds them all in memory at once
    rm -rf "$B/od"; mkdir -p "$B/od"
    (cd "$GEN" && find . -name "*.d" | sort > "$B/dfiles")
    split -n l/4 "$B/dfiles" "$B/dbatch."
    for f in "$B"/dbatch.*; do
        (cd "$GEN" && ldc2 -c -oq -O -od="$B/od" -I. $(cat "$f"))
    done
    rm -f "$B/libbinding_ldc2.a"; ar rcs "$B/libbinding_ldc2.a" "$B"/od/*.o
    done_ binding
fi

# ---- the app ---------------------------------------------------------------------------------------
if ! step app; then
    ldc2 -O -release -of="$APP/qml-whats-ldc2" "$APP/source/app.d" "$SQD/source/solidqml/host.d" "$APP"/source/qmlwhats/*.d \
        -I"$SQD/source" -I"$APP/source" -I"$GEN" -J"$APP/assets/icons" -J"$APP/assets" \
        -L--gc-sections -L--as-needed -L--start-group -L="$B/libbinding_ldc2.a" -L="$B/libshims.a" -L--end-group \
        -L-L"$W/solidqml" -L-lsolidqml $(pkg-config --libs $MODS | sed -E 's/(^| )-L/\1-L-L/g; s/(^| )-l/\1-L-l/g') \
        -L-lstdc++ -L-lsystemd
    rm -rf "$APP/qml"; mkdir -p "$APP/qml"; cp "$APP"/ui/qml/*.qml "$APP/qml/"
    done_ app
fi

# ---- the AppImage (tools/appimage.sh, with this Qt) --------------------------------------------------
[ -x "$TOOLS/appimagetool" ] || {
    curl -sSL -o "$TOOLS/appimagetool" https://github.com/AppImage/appimagetool/releases/download/continuous/appimagetool-x86_64.AppImage
    chmod +x "$TOOLS/appimagetool"; }
export QMAKE=$Q/bin/qmake APPIMAGETOOL=$TOOLS/appimagetool XDG_CACHE_HOME=$W/cache APPIMAGE_EXTRACT_AND_RUN=1
mkdir -p "$W/cache/qml-whats-build/tools"
for t in linuxdeploy linuxdeploy-plugin-qt; do
    [ -s "$TOOLS/$t-x86_64.AppImage" ] || curl -sSL -o "$TOOLS/$t-x86_64.AppImage" \
        "https://github.com/linuxdeploy/$t/releases/download/continuous/$t-x86_64.AppImage"
    chmod +x "$TOOLS/$t-x86_64.AppImage"
    cp -f "$TOOLS/$t-x86_64.AppImage" "$W/cache/qml-whats-build/tools/"
done
export LD_LIBRARY_PATH=$Q/lib:$W/solidqml   # linuxdeploy reads the binary's ldd
(cd "$APP" && ./tools/appimage.sh "$W/solidqml")
cp "$APP/QWhats-x86_64.AppImage" "$OUT/QWhats-x86_64.AppImage"
echo "== AppImage: $OUT/QWhats-x86_64.AppImage"
